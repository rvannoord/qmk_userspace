"""Monitor ERP's logos at panel size -> art/monitor_art.c / .h

    python3 -I tools/panel/gen_monitor.py <outdir>

Reads the four finished grids in tools/panel/monitor/ ('#' lit, '.' dark, a line starting // a note; draft_monitor.py
drafts them from the brand files, which stay out of git) and emits:

- u_monitor_screen: the slave's three Monitor screens, each a whole 128x64 panel in page
  format with its logo centred: the horizontal logo, the stacked logo, "Monitor your future".
- u_monitor_band: the horizontal logo for the master's base band, in page format, as many
  pages as its rows need; the master places it at any row.

docs/layout.md, "The Monitor ERP screens", says how they were drawn.
"""

import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
GRIDS = HERE / 'monitor'
W, H = 128, 64
SCREENS = ['horizontal', 'stacked', 'future']


def read(name):
    rows = [r for r in (GRIDS / f'{name}.txt').read_text().split('\n') if r and not r.startswith('//')]
    if len({len(r) for r in rows}) != 1 or set(''.join(rows)) - {'#', '.'}:
        raise SystemExit(f'gen_monitor: {name}.txt is not a rectangle of # and .')
    return [[c == '#' for c in r] for r in rows]


def pages(grid, w, h):
    """Page format: one byte a column, bit 0 the top row, page after page."""
    out = []
    for p in range((h + 7) // 8):
        for x in range(w):
            b = 0
            for k in range(8):
                y = p * 8 + k
                if y < h and grid[y][x]:
                    b |= 1 << k
            out.append(b)
    return out


def centred(grid):
    h, w = len(grid), len(grid[0])
    if w > W or h > H:
        raise SystemExit(f'gen_monitor: a {w}x{h} logo does not fit the panel')
    x0, y0 = (W - w) // 2, (H - h) // 2
    screen = [[False] * W for _ in range(H)]
    for y in range(h):
        for x in range(w):
            screen[y0 + y][x0 + x] = grid[y][x]
    return screen


def hexrows(data, per=16, indent='        '):
    return '\n'.join(indent + ', '.join(f'0x{b:02x}' for b in data[i:i + per]) + ','
                     for i in range(0, len(data), per))


def main(outdir):
    outdir = pathlib.Path(outdir)
    screens = [pages(centred(read(n)), W, H) for n in SCREENS]
    band = read('band')
    bh, bw = len(band), len(band[0])
    band_bytes = pages(band, bw, bh)
    banner = ("// Generated by tools/panel/gen_monitor.py from tools/panel/monitor/*.txt.\n"
              "// Do not edit: redraw the grids instead.\n"
              "//\n"
              "// Monitor ERP's logos, the author's workplace's, drawn by hand at panel size from the brand\n"
              "// files (docs/layout.md, \"The Monitor ERP screens\"). Page format: one byte a column,\n"
              "// bit 0 the top row.\n")
    with open(outdir / 'monitor_art.h', 'w') as f:
        f.write(banner)
        f.write('\n#pragma once\n\n#include <stdint.h>\n#include "progmem.h"\n\n')
        f.write('// The slave\'s Monitor screens, whole panels, in this order.\n'
                'enum u_monitor_screen { U_MONITOR_HORIZONTAL, U_MONITOR_STACKED, U_MONITOR_FUTURE, U_MONITOR_COUNT };\n'
                'extern const uint8_t PROGMEM u_monitor_screen[U_MONITOR_COUNT][1024];\n\n')
        f.write('// The horizontal logo for the master\'s base band.\n'
                f'#define U_MONITOR_BAND_W     {bw}\n'
                f'#define U_MONITOR_BAND_H     {bh}\n'
                f'#define U_MONITOR_BAND_PAGES {(bh + 7) // 8}\n'
                'extern const uint8_t PROGMEM u_monitor_band[U_MONITOR_BAND_PAGES * U_MONITOR_BAND_W];\n')
    with open(outdir / 'monitor_art.c', 'w') as f:
        f.write(banner)
        f.write('\n#include "monitor_art.h"\n\n')
        f.write('const uint8_t PROGMEM u_monitor_screen[U_MONITOR_COUNT][1024] = {\n')
        for name, data in zip(SCREENS, screens):
            lit = sum(bin(b).count('1') for b in data)
            f.write(f'    {{   // {name}, {lit} lit\n{hexrows(data)}\n    }},\n')
        f.write('};\n\n')
        lit = sum(bin(b).count('1') for b in band_bytes)
        f.write(f'// {bw}x{bh}, {lit} lit\n')
        f.write('const uint8_t PROGMEM u_monitor_band[U_MONITOR_BAND_PAGES * U_MONITOR_BAND_W] = {\n')
        f.write(hexrows(band_bytes, indent='    ') + '\n};\n')
    print(f'gen_monitor: 3 screens and a {bw}x{bh} band -> {outdir}')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
