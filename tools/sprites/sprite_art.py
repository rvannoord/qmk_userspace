"""Hand-drawn sprite grids -> art/<name>_art.c / .h

    python3 -I tools/sprites/sprite_art.py <name> <grids.txt> <outdir>

The grids: a line `= frame` starts a frame, then rows of '#' (lit) and '.' (dark); a line
starting // is a note. Every frame is the same size, and its bottom row is the row the
sprite stands on.

Emits, per frame, the ink and a mask in page format (one byte a column, bit 0 the top
row): the mask is the filled silhouette, the ink plus everything it encloses, so what is
drawn behind the sprite (the weather) can stop at its outline. The frames' enum follows
the file's order. The banner names where the drawing comes from; see VENDORED.md.
"""

import pathlib
import sys

BANNERS = {
    'goat': ("// The goat, from infinition's Bjorn (github.com/infinition/Bjorn), MIT licensed,\n"
             "// \"Copyright (c) 2024 infinition\". Redrawn by hand at panel size from the goat in\n"
             "// his IDLE9 and IDLE10 frames; see VENDORED.md and docs/layout.md.\n"),
}


def read(path):
    frames, name, rows = [], None, []
    for line in pathlib.Path(path).read_text().splitlines():
        s = line.strip()
        if not s or s.startswith('//'):
            continue
        if s.startswith('='):
            if name:
                frames.append((name, rows))
            name, rows = s[1:].strip(), []
        else:
            rows.append(s)
    if name:
        frames.append((name, rows))
    sizes = {(len(r), len(r[0])) for _, r in frames}
    for n, r in frames:
        if len({len(x) for x in r}) != 1 or set(''.join(r)) - {'#', '.'}:
            raise SystemExit(f'sprite_art: {n} is not a rectangle of # and .')
    if len(sizes) != 1:
        raise SystemExit(f'sprite_art: the frames differ in size: {sorted(sizes)}')
    return frames


def silhouette(rows):
    """The ink plus everything it encloses: whatever dark cell the outside cannot reach."""
    h, w = len(rows), len(rows[0])
    out = [[False] * w for _ in range(h)]
    todo = [(x, y) for x in range(w) for y in (0, h - 1)] + [(x, y) for y in range(h) for x in (0, w - 1)]
    while todo:
        x, y = todo.pop()
        if 0 <= x < w and 0 <= y < h and not out[y][x] and rows[y][x] == '.':
            out[y][x] = True
            todo += [(x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)]
    return [[not out[y][x] for x in range(w)] for y in range(h)]


def pages(grid, w, h):
    data = []
    for p in range((h + 7) // 8):
        for x in range(w):
            b = 0
            for k in range(8):
                y = p * 8 + k
                if y < h and grid[y][x]:
                    b |= 1 << k
            data.append(b)
    return data


def hexrows(data, indent='        '):
    return '\n'.join(indent + ', '.join(f'0x{b:02x}' for b in data[i:i + 16]) + ','
                     for i in range(0, len(data), 16))


def main(name, src, outdir):
    frames = read(src)
    h, w = len(frames[0][1]), len(frames[0][1][0])
    up = name.upper()
    nbytes = ((h + 7) // 8) * w
    banner = (f"// Generated by tools/sprites/sprite_art.py from tools/sprites/{pathlib.Path(src).name}.\n"
              "// Do not edit: redraw the grids instead.\n//\n" + BANNERS.get(name, '') +
              "// Page format, one byte a column, bit 0 the top row; the bottom row is the one the\n"
              "// sprite stands on. Ink is lit; the mask is the filled silhouette.\n")
    outdir = pathlib.Path(outdir)
    with open(outdir / f'{name}_art.h', 'w') as f:
        f.write(banner + '\n#pragma once\n\n#include <stdint.h>\n#include "progmem.h"\n\n')
        f.write(f'#define U_{up}_W     {w}\n#define U_{up}_H     {h}\n'
                f'#define U_{up}_PAGES {(h + 7) // 8}\n#define U_{up}_BYTES {nbytes}\n\n')
        f.write(f'enum u_{name}_frame {{\n')
        for n, _ in frames:
            f.write(f'    U_{up}_{n.upper()},\n')
        f.write(f'    U_{up}_FRAMES,\n}};\n\n')
        f.write(f'extern const uint8_t PROGMEM u_{name}[U_{up}_FRAMES][U_{up}_BYTES];\n')
        f.write(f'extern const uint8_t PROGMEM u_{name}_mask[U_{up}_FRAMES][U_{up}_BYTES];\n')
    with open(outdir / f'{name}_art.c', 'w') as f:
        f.write(banner + f'\n#include "{name}_art.h"\n')
        for arr, fn in ((f'u_{name}', lambda r: [[c == '#' for c in row] for row in r]),
                        (f'u_{name}_mask', silhouette)):
            f.write(f'\nconst uint8_t PROGMEM {arr}[U_{up}_FRAMES][U_{up}_BYTES] = {{\n')
            for n, rows in frames:
                grid = fn(rows)
                lit = sum(sum(1 for c in row if c) for row in grid)
                f.write(f'    {{   // {n}, {lit} lit\n{hexrows(pages(grid, w, h))}\n    }},\n')
            f.write('};\n')
    print(f'sprite_art: {len(frames)} frames of {w}x{h} -> {outdir}/{name}_art.c')


if __name__ == '__main__':
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)
    main(*sys.argv[1:])
