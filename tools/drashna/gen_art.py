"""drashna's OLED art -> six art/ files for the keymap

    python3 -I gen_art.py <drashna-src> <drashna-modules> <outdir>

<drashna-src> is a sparse clone of drashna/qmk_userspace and <drashna-modules> one of
drashna/qmk_modules, both at the commits pinned below; VENDORED.md has the recipe.
Writes, each as a .c and a .h:

    drashna_icons   the 12x16 Windows and Apple logos; mute, speaker and bulb at 12x8
    kitty_art       the striped and the small kitty, sleep / paw / watch / bounce
    status_frame    the status sheet's header, footer and side border
    bongo_art       bongo cat, 128x32
    mario_art       Mario, the sixteen Yoshi frames the scene uses, Bullet Bill
    matrix_art      the 128x64 matrix rain, 72 frames

Everything stays in the sources' own page format: one byte a column, bit 0 at the
top, each 8-row page in turn. The arrays' trailing pad bytes ([32+1], [1024+1]) are
dropped, after checking that they are zero. Frame orders are not baked in: they are
the renderers' business, so only the sets' boundaries are named here.

The sources are checked rather than trusted: a frame the scene relies on that has
gone empty, an empty slot that has filled up, or the small kitty's paw frames no
longer being copies of its sleep frames all stop the run, because each of those
would mean drashna changed the art and the renderers' assumptions with it.
"""

import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import csource as cs  # noqa: E402

DRASHNA_SHA = '0903be5b3c56a394dbfb27b8095bc5ad747b8d98'
MODULES_SHA = 'ee2c35bcbb7d8b8be108c93c5b8715ea1a2c020c'
OLED_DIR = 'users/drashna/display/oled'
ME = 'tools/drashna/gen_art.py'


def lit(vals):
    return sum(bin(v).count('1') for v in vals)


def bbox(vals, w, h):
    """(x, y, w, h) of the lit pixels of a page-format sprite."""
    xs, ys = [], []
    for y in range(h):
        for x in range(w):
            if (vals[(y // 8) * w + x] >> (y % 8)) & 1:
                xs.append(x)
                ys.append(y)
    if not xs:
        return None
    return min(xs), min(ys), max(xs) - min(xs) + 1, max(ys) - min(ys) + 1


def sprite(values, base, pages, stride, w):
    """One page-format sprite out of an array of [pages][stride] rows, pad dropped."""
    out = []
    for p in range(pages):
        row = values[base + p * stride: base + (p + 1) * stride]
        if any(row[w:]):
            raise SystemExit(f'gen_art: a pad byte is not zero at {base + p * stride}')
        out += row[:w]
    return out


def banner(source, what, notice):
    return ''.join([
        f'// Generated by {ME} from {source}.\n',
        '// Do not edit: regenerate instead. Sources and licence in VENDORED.md.\n',
        '//\n',
        *[f'// {line}\n' if line else '//\n' for line in what],
        '//\n',
        *[f'{line}\n' for line in notice],
    ])


def write(outdir, name, head, h_body, c_body):
    (outdir / f'{name}.h').write_text(
        head + '\n#pragma once\n\n#include <stdint.h>\n#include "progmem.h"\n\n' + h_body)
    (outdir / f'{name}.c').write_text(head + f'\n#include "{name}.h"\n\n' + c_body)
    print(f'  {name}.c / .h')


def array(decl, frames, labels):
    """`const uint8_t PROGMEM <decl> = {...};` with one labelled block per frame."""
    if len(frames) == 1 and labels[0] is None:
        return f'const uint8_t PROGMEM {decl} = {{\n' + cs.c_bytes(frames[0]) + '};\n'
    out = f'const uint8_t PROGMEM {decl} = {{\n'
    for vals, label in zip(frames, labels):
        out += f'    {{   // {label}, {lit(vals)} lit\n' + cs.c_bytes(vals, '        ') + '    },\n'
    return out + '};\n'


# ---------------------------------------------------------------- the font's icons


def icons(src, outdir):
    path = src / OLED_DIR / 'drashna_font.h'
    font = cs.load(path)['font'].values

    def cell(c):
        return font[c * 6:c * 6 + 6]

    def pair(top, bottom=None):
        """Two 6-px cells side by side, over two more for a 16-row logo."""
        vals = cell(top) + cell(top + 1)
        return vals + cell(bottom) + cell(bottom + 1) if bottom is not None else vals

    logos = [('WINDOWS', pair(0x97, 0xb7), '0x97 0x98 over 0xb7 0xb8'),
             ('APPLE', pair(0x95, 0xb5), '0x95 0x96 over 0xb5 0xb6')]
    small = [('MUTE', pair(0xe0), 'speaker, struck through: 0xe0 0xe1'),
             ('SPEAKER', pair(0xe2), 'speaker with sound: 0xe2 0xe3'),
             ('BULB', pair(0xf0), 'bulb, lit: 0xf0 0xf1')]
    for name, vals, _ in logos + small:
        if not lit(vals):
            raise SystemExit(f'gen_art: the {name} icon is empty in drashna_font.h')

    head = banner(f"drashna's {path.name}",
                  ["Icons out of drashna's OLED font, each a pair of its 6x8 cells, kept in",
                   'page format: one byte a column, bit 0 at the top. The OS logos are two',
                   'pages of 12 columns, the small icons one.'],
                  cs.header(path))
    h = ('#define U_OS_LOGO_W     12\n#define U_OS_LOGO_PAGES 2\n\n'
         'enum u_os_logo {\n' + ''.join(f'    U_OS_LOGO_{n},    // {note}\n' for n, _, note in logos)
         + '    U_OS_LOGO_COUNT,\n};\n\n'
         'extern const uint8_t PROGMEM u_os_logo[U_OS_LOGO_COUNT][U_OS_LOGO_PAGES * U_OS_LOGO_W];\n\n'
         '#define U_ICON12_W 12\n\n'
         'enum u_icon12 {\n' + ''.join(f'    U_ICON12_{n},    // {note}\n' for n, _, note in small)
         + '    U_ICON12_COUNT,\n};\n\n'
         'extern const uint8_t PROGMEM u_icon12[U_ICON12_COUNT][U_ICON12_W];\n')
    c = (array('u_os_logo[U_OS_LOGO_COUNT][U_OS_LOGO_PAGES * U_OS_LOGO_W]',
               [v for _, v, _ in logos], [n for n, _, _ in logos]) + '\n'
         + array('u_icon12[U_ICON12_COUNT][U_ICON12_W]', [v for _, v, _ in small], [n for n, _, _ in small]))
    write(outdir, 'drashna_icons', head, h, c)


# ---------------------------------------------------------------- the kitties

# drashna's six types, of which the master uses the first four. drashna's names in
# brackets; the English ones are what docs/layout.md calls them.
MOODS = [('SLEEP', 'sleep'), ('PAW', 'kaki'), ('WATCH', 'mati'), ('BOUNCE', 'awake')]
PETS = [('STRIPED', 0, 'tora, the status sheet\'s'), ('SMALL', 2, 'luna, the bands\'')]


def kitties(src, outdir):
    path = src / OLED_DIR / 'oled_assets.h'
    pa = cs.load(path)['pet_animiations']
    pets_n, types_n, slots, pages, stride = pa.dims
    if (types_n, slots, pages, stride) != (6, 3, 4, 33):
        raise SystemExit(f'gen_art: pet_animiations is {pa.dims}, expected [][6][3][4][33]')

    def frame(pet, t, i):
        return sprite(pa.values, (((pet * types_n + t) * slots + i) * pages) * stride, pages, stride, 32)

    h = '#define U_KITTY_W     32\n#define U_KITTY_BYTES 128    // 32x32, four pages\n\n'
    h += 'enum u_kitty_mood {\n' + ''.join(f'    U_KITTY_{n},    // drashna\'s "{d}"\n' for n, d in MOODS)
    h += '    U_KITTY_MOOD_COUNT,\n};\n\n'
    h += '// Where a mood\'s frames start in its pet\'s array, and how many there are.\n'
    h += 'typedef struct {\n    uint8_t first;\n    uint8_t count;\n} u_kitty_run_t;\n'
    c = ''
    for name, pet, note in PETS:
        store, runs = [], []
        for t, (mood, _) in enumerate(MOODS):
            got = [frame(pet, t, i) for i in range(slots)]
            used = [f for f in got if lit(f)]
            if any(lit(f) for f in got[len(used):]):
                raise SystemExit(f'gen_art: pet {pet} {mood} has an empty slot between frames')
            if not used:
                raise SystemExit(f'gen_art: pet {pet} {mood} has no frames')
            # luna's paw frames are her sleep frames, byte for byte: point at those
            # rather than store them twice, and say so where the renderer will look
            if used in [store[r[0]:r[0] + r[1]] for r in runs]:
                at = [store[r[0]:r[0] + r[1]] for r in runs].index(used)
                runs.append((runs[at][0], runs[at][1], f'the same frames as {MOODS[at][0]}'))
                continue
            runs.append((len(store), len(used), None))
            store += used
        if name == 'SMALL' and runs[1][2] is None:
            raise SystemExit('gen_art: the small kitty\'s paw frames are no longer its sleep frames')
        lname = name.lower()
        h += (f'\n// {note}: {len(store)} frames\n'
              f'#define U_KITTY_{name}_FRAMES {len(store)}\n'
              f'extern const uint8_t PROGMEM u_kitty_{lname}[U_KITTY_{name}_FRAMES][U_KITTY_BYTES];\n'
              f'extern const u_kitty_run_t u_kitty_{lname}_moods[U_KITTY_MOOD_COUNT];\n')
        labels = []
        for (mood, _), (first, count, same) in zip(MOODS, runs):
            if same is None:
                labels += [f'{mood} {i}' for i in range(count)]
        c += array(f'u_kitty_{lname}[U_KITTY_{name}_FRAMES][U_KITTY_BYTES]', store, labels) + '\n'
        c += f'const u_kitty_run_t u_kitty_{lname}_moods[U_KITTY_MOOD_COUNT] = {{\n'
        for (mood, _), (first, count, same) in zip(MOODS, runs):
            c += f'    [U_KITTY_{mood}] = {{{first}, {count}}},' + (f'    // {same}' if same else '') + '\n'
        c += '};\n\n'

    head = banner(f"drashna's {path.name}, pet_animiations",
                  ["Two of drashna's three 32x32 kitties, the four moods the master uses, in",
                   'page format: one byte a column, bit 0 at the top, four pages. drashna\'s',
                   'speeds were sleep up to 10 WPM, paw to 40, watch to 60, bounce above;',
                   'docs/oled-v3.md D9 decides which tiers drive them here.'],
                  cs.header(path) + ['// Images credit j-inc (James Incandenza) and pixelbenny, as drashna\'s file says.'])
    write(outdir, 'kitty_art', head, h, c.rstrip('\n') + '\n')


# ---------------------------------------------------------------- the status sheet's frame


def status_frame(src, outdir):
    path = src / OLED_DIR / 'oled_assets.h'
    a = cs.load(path)
    header = cs.frames(a['header_image'].values, 1, 129, 128)[0]
    footer = cs.frames(a['footer_image2'].values, 1, 129, 128)[0]
    border = cs.frames(a['display_border'].values, 1, 4, 3)[0]
    for k in ('header_image', 'footer_image2', 'display_border'):
        if a[k].values[-1]:
            raise SystemExit(f'gen_art: {k} has a non-zero pad byte')
    head = banner(f"drashna's {path.name}",
                  ["The frame around drashna's status screen: a 128-wide header for page 0, a",
                   'footer for page 7 (footer_image2, the filled one), and the 3-column pattern',
                   'drashna draws down both sides. Page format, bit 0 at the top.'],
                  cs.header(path))
    h = ('#define U_STATUS_FRAME_W 128\n\n'
         'extern const uint8_t PROGMEM u_status_header[U_STATUS_FRAME_W];\n'
         'extern const uint8_t PROGMEM u_status_footer[U_STATUS_FRAME_W];\n\n'
         '// One byte a column, the same on every page from 1 to 6.\n'
         '#define U_STATUS_BORDER_W 3\n'
         'extern const uint8_t PROGMEM u_status_border[U_STATUS_BORDER_W];\n')
    c = (array('u_status_header[U_STATUS_FRAME_W]', [header], [None]) + '\n'
         + array('u_status_footer[U_STATUS_FRAME_W]', [footer], [None]) + '\n'
         + array('u_status_border[U_STATUS_BORDER_W]', [border], [None]))
    write(outdir, 'status_frame', head, h, c)


# ---------------------------------------------------------------- bongo cat


def bongo(mods, outdir):
    path = mods / 'bongocats' / 'bongocat_assets.c'
    a = cs.load(path, ['__attribute__(x)='])
    sets = [('IDLE', 'bongocats_idle', 5), ('PREP', 'bongocats_prep', 1), ('TAP', 'bongocats_tap', 2)]
    h = ('#define U_BONGO_W     128\n#define U_BONGO_PAGES 4\n'
         '#define U_BONGO_BYTES 512    // 128x32\n\n')
    c = ''
    for name, src_name, n in sets:
        arr = a[src_name]
        if arr.dims != [n, 512]:
            raise SystemExit(f'gen_art: {src_name} is {arr.dims}, expected [{n}][512]')
        frames = cs.frames(arr.values, n, 512, 512)
        if not all(lit(f) for f in frames):
            raise SystemExit(f'gen_art: an empty frame in {src_name}')
        lname = name.lower()
        h += (f'#define U_BONGO_{name}_FRAMES {n}\n'
              f'extern const uint8_t PROGMEM u_bongo_{lname}[U_BONGO_{name}_FRAMES][U_BONGO_BYTES];\n')
        c += array(f'u_bongo_{lname}[U_BONGO_{name}_FRAMES][U_BONGO_BYTES]', frames,
                   [f'{name} {i}' for i in range(n)]) + '\n'
    notice = [line.replace('SPD-License', 'SPDX-License') for line in cs.header(path)]
    head = banner(f"the bongocats module's {path.name}",
                  ['Bongo cat, 128x32, in page format: one byte a column, bit 0 at the top, four',
                   'pages. Idle below 10 WPM, the prep frame up to 20, the tap frames above.'],
                  notice)
    write(outdir, 'bongo_art', head, h, c.rstrip('\n') + '\n')


# ---------------------------------------------------------------- Mario, Yoshi and Bill

MARIO = ['STAND', 'STAND_ALT', 'STEP', 'JUMP']
# drashna's five Yoshi sets and how many of each set's five slots are drawn
YOSHI = [('IDLE', 3), ('READY', 5), ('FLY', 3), ('HIDE', 3), ('RUN', 2)]


def mario(src, outdir):
    path = src / OLED_DIR / 'oled_assets.h'
    a = cs.load(path)

    ma = a['mario_animation']
    if ma.dims != [4, 4, 16]:
        raise SystemExit(f'gen_art: mario_animation is {ma.dims}')
    marios = [ma.values[i * 64:(i + 1) * 64] for i in range(4)]

    ya = a['yoshi_animation']
    if ya.dims != [5, 5, 4, 33]:
        raise SystemExit(f'gen_art: yoshi_animation is {ya.dims}')
    yoshis, firsts = [], []
    for s, (name, n) in enumerate(YOSHI):
        got = [sprite(ya.values, (s * 5 + f) * 4 * 33, 4, 33, 32) for f in range(5)]
        if not all(lit(f) for f in got[:n]) or any(lit(f) for f in got[n:]):
            raise SystemExit(f'gen_art: Yoshi {name} no longer has exactly {n} drawn frames')
        firsts.append(len(yoshis))
        yoshis += got[:n]

    bill = sprite(a['bullet_bill_logo'].values, 0, 3, 33, 32)

    for label, frames, w, h in [('Mario', marios, 16, 32), ('Yoshi', yoshis, 32, 32), ('Bill', [bill], 32, 24)]:
        boxes = sorted({bbox(f, w, h) for f in frames})
        print(f'    {label}: {len(frames)} frames, lit boxes {boxes}')

    head = banner(f"drashna's {path.name}",
                  ['The Mario, Yoshi and Bullet Bill scene, in page format: one byte a column,',
                   "bit 0 at the top. drashna's frame orders are tables in the renderer, not",
                   "here; only the Yoshi sets' boundaries are named. Mario and Yoshi face right,",
                   'Bill faces left.'],
                  cs.header(path) + ['// Mario, Yoshi and Bullet Bill are Nintendo\'s characters; these are fan-art sprites.'])
    h = ('#define U_MARIO_W     16\n#define U_MARIO_PAGES 4\n#define U_MARIO_BYTES 64    // 16x32\n\n'
         'enum u_mario_frame {\n' + ''.join(f'    U_MARIO_{n},\n' for n in MARIO)
         + '    U_MARIO_FRAMES,\n};\n\n'
         'extern const uint8_t PROGMEM u_mario[U_MARIO_FRAMES][U_MARIO_BYTES];\n\n'
         '#define U_YOSHI_W     32\n#define U_YOSHI_PAGES 4\n#define U_YOSHI_BYTES 128    // 32x32\n\n'
         "// drashna's five sets, with the empty slots dropped: where each starts, and its length.\n"
         + ''.join(f'#define U_YOSHI_{n} {firsts[i]}\n#define U_YOSHI_{n}_N {c}\n' for i, (n, c) in enumerate(YOSHI))
         + f'#define U_YOSHI_FRAMES {len(yoshis)}\n\n'
         'extern const uint8_t PROGMEM u_yoshi[U_YOSHI_FRAMES][U_YOSHI_BYTES];\n\n'
         '#define U_BILL_W     32\n#define U_BILL_PAGES 3\n#define U_BILL_BYTES 96    // 32x24\n\n'
         'extern const uint8_t PROGMEM u_bill[U_BILL_BYTES];\n')
    ylabels = [f'{n} {i}' for n, cnt in YOSHI for i in range(cnt)]
    c = (array('u_mario[U_MARIO_FRAMES][U_MARIO_BYTES]', marios, MARIO) + '\n'
         + array('u_yoshi[U_YOSHI_FRAMES][U_YOSHI_BYTES]', yoshis, ylabels) + '\n'
         + array('u_bill[U_BILL_BYTES]', [bill], [None]))
    write(outdir, 'mario_art', head, h, c)


# ---------------------------------------------------------------- the matrix rain


def matrix(src, outdir):
    path = src / OLED_DIR / 'screensavers' / 'matrix_scroll.h'
    arr = cs.load(path, ['OLED_DISPLAY_128X64'])['screensaver']
    if arr.dims != [72, 1025]:
        raise SystemExit(f'gen_art: the 128x64 screensaver is {arr.dims}, expected [72][1025]')
    if any(arr.values[i * 1025 + 1024] for i in range(72)):
        raise SystemExit('gen_art: a screensaver pad byte is not zero')
    frames = cs.frames(arr.values, 72, 1025, 1024)
    head = banner(f"drashna's screensavers/{path.name}, the OLED_DISPLAY_128X64 branch",
                  ['The matrix rain, 72 whole frames of the 128x64 panel, in the driver\'s own',
                   'buffer format: eight pages of 128 columns, bit 0 at the top. drashna runs it',
                   'at 30 ms a frame; the split\'s render tick is 50 ms.'],
                  cs.header(path))
    h = ('#define U_MATRIX_FRAMES 72\n#define U_MATRIX_BYTES  1024    // 128x64\n\n'
         'extern const uint8_t PROGMEM u_matrix[U_MATRIX_FRAMES][U_MATRIX_BYTES];\n')
    c = array('u_matrix[U_MATRIX_FRAMES][U_MATRIX_BYTES]', frames, [f'frame {i}' for i in range(72)])
    write(outdir, 'matrix_art', head, h, c)


def main(src, mods, outdir):
    src, mods, outdir = pathlib.Path(src), pathlib.Path(mods), pathlib.Path(outdir)
    cs.pinned(src, DRASHNA_SHA)
    cs.pinned(mods, MODULES_SHA)
    icons(src, outdir)
    kitties(src, outdir)
    status_frame(src, outdir)
    bongo(mods, outdir)
    mario(src, outdir)
    matrix(src, outdir)
    print(f'-> {outdir}')


if __name__ == '__main__':
    if len(sys.argv) != 4:
        raise SystemExit(__doc__.split('\n\n')[1])
    main(*sys.argv[1:])
