"""The world layer's sprites -> world_art.c / .h

    python3 -I gen_world.py <outdir>

Reads `sprites.txt`, which is committed beside this file, and needs nothing
installed. The sprites were authored in the design study and dumped once; this
generator only changes their representation.

## Row-major, not page format

Every other generated asset here is in the driver's page format, because every
other asset is blitted at a fixed position. These are different: the rain, snow
and star fields **scroll vertically**, so at render time row `y` of the panel
takes row `(y + scroll) % h` of the tile. A page byte holds eight rows at once,
so an arbitrary vertical offset would mean unpacking and repacking every byte on
every step - the format would be fighting the only thing these assets do.

Stored row-major, one bit per pixel, the scroll is an index. The compositor pays
the page-format cost once, when it writes into `u_canvas`.

## Why the fields are 128 wide and authored, not tiled from 64

A 63 px pattern repeated across 128 shows the same thing twice and reads as
wallpaper immediately. The fields are authored at full width with blue-noise
placement and tile only *vertically*. That also disposes of the x=63 seam
question for them: they are pixel-exact rather than dithered, so the rule about
dithering each half separately - which exists because Floyd-Steinberg diffuses
error rightward - does not apply. There is no error to diffuse.

Snow is the exception that proves it: its drift is a dithered asset and does
cross the seam, so that one is dithered in two independent 64-wide passes.
"""

import pathlib
import sys

ROW_BYTES = 16          # 128 px / 8


def read_sprites(path):
    """-> [(name, w, h, note, rows)] in file order."""
    out, cur = [], None
    for line in pathlib.Path(path).read_text().splitlines():
        # A grid row is recognised by matching the width its header declared, not
        # merely by being made of '#' and '.'. A bare '#' comment line is both, and
        # the looser test reads it as a one-pixel row - the same trap as
        # tools/panel/icon_overrides.txt, where a row of solid ink looks like a
        # comment. Anchoring to the declared width makes the two unambiguous.
        if cur is not None and len(line) == cur[1] and set(line) <= {'#', '.'}:
            cur[4].append(line)
            continue
        s = line.strip()
        if not s or s.startswith('#'):
            continue
        if not s.startswith('['):
            raise SystemExit(f'gen_world: unexpected line {s!r}')
        head, _, rest = s[1:].partition(']')
        note = rest.split('#', 1)[1].strip() if '#' in rest else ''
        spec = dict(kv.split('=') for kv in rest.split('#')[0].split())
        cur = [head, int(spec['w']), int(spec['h']), note, []]
        out.append(cur)
    for name, w, h, _, rows in out:
        if len(rows) != h or any(len(r) != w for r in rows):
            raise SystemExit(f'gen_world: {name} is not {w}x{h}')
    return out


def pack(rows, w):
    """Row-major, bit 7 of each byte is the leftmost pixel of its group of 8."""
    stride = (w + 7) // 8
    out = bytearray()
    for row in rows:
        for b in range(stride):
            byte = 0
            for k in range(8):
                x = b * 8 + k
                if x < w and row[x] == '#':
                    byte |= 0x80 >> k
            out.append(byte)
    return bytes(out), stride


def main(outdir):
    here = pathlib.Path(__file__).resolve().parent
    sprites = read_sprites(here / 'sprites.txt')
    outdir = pathlib.Path(outdir)

    banner = ("// Generated by tools/world/gen_world.py from tools/world/sprites.txt.\n"
              "// Do not edit: change the sprites file and regenerate.\n"
              "//\n"
              "// Row-major, one bit a pixel, bit 7 leftmost - NOT the driver's page\n"
              "// format, because these scroll vertically and a page byte holds eight\n"
              "// rows at once. See the generator for the reasoning.\n")

    fields = [s for s in sprites if not s[0].startswith('LEAF')]
    leaves = [s for s in sprites if s[0].startswith('LEAF')]

    with open(outdir / 'world_art.h', 'w') as f:
        f.write(banner)
        f.write('\n#pragma once\n\n#include <stdint.h>\n#include "progmem.h"\n\n')
        f.write(f'#define U_WORLD_ROW_BYTES {ROW_BYTES}\n\n')
        for name, w, h, note, _ in fields:
            f.write(f'// {note}\n')
            f.write(f'#define U_{name}_W {w}\n#define U_{name}_H {h}\n')
            f.write(f'extern const uint8_t PROGMEM u_{name.lower()}[U_{name}_H * U_WORLD_ROW_BYTES];\n\n')
        lw, lh = leaves[0][1], leaves[0][2]
        f.write('// Tumble frames, cycled by fall progress rather than by a timer, so a\n'
                '// leaf that falls slowly also turns slowly.\n')
        f.write(f'#define U_LEAF_W {lw}\n#define U_LEAF_H {lh}\n')
        f.write(f'#define U_LEAF_STRIDE {(lw + 7) // 8}\n#define U_LEAF_FRAMES {len(leaves)}\n')
        f.write('extern const uint8_t PROGMEM u_leaf[U_LEAF_FRAMES][U_LEAF_H * U_LEAF_STRIDE];\n')

    with open(outdir / 'world_art.c', 'w') as f:
        f.write(banner)
        f.write('\n#include "world_art.h"\n\n')
        total = 0
        for name, w, h, note, rows in fields:
            data, stride = pack(rows, w)
            total += len(data)
            ink = sum(r.count('#') for r in rows)
            f.write(f'// {name}: {w}x{h}, {ink} ink. {note}\n')
            f.write(f'const uint8_t PROGMEM u_{name.lower()}[U_{name}_H * U_WORLD_ROW_BYTES] = {{\n')
            for i in range(0, len(data), stride):
                f.write('    ' + ', '.join(f'0x{b:02x}' for b in data[i:i + stride]) + ',\n')
            f.write('};\n\n')
        f.write(f'const uint8_t PROGMEM u_leaf[U_LEAF_FRAMES][U_LEAF_H * U_LEAF_STRIDE] = {{\n')
        for name, w, h, note, rows in leaves:
            data, stride = pack(rows, w)
            total += len(data)
            f.write(f'    {{   // {name}, {sum(r.count("#") for r in rows)} ink\n')
            for i in range(0, len(data), stride):
                f.write('        ' + ', '.join(f'0x{b:02x}' for b in data[i:i + stride]) + ',\n')
            f.write('    },\n')
        f.write('};\n')

    for name, w, h, _, rows in sprites:
        print(f'  {name:7} {w:3}x{h:<3} {sum(r.count("#") for r in rows):4} ink')
    print(f'{len(sprites)} sprites, {total} bytes -> {outdir}')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        raise SystemExit(__doc__.split('\n\n')[0])
    main(sys.argv[1])
